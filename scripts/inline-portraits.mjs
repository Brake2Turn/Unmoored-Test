/**
 * Bakes `assets/portraits/*.png` into `lib/portraits.ts` as data URIs.
 *
 *     node scripts/inline-portraits.mjs
 *
 * Run it after adding a portrait with `make-portrait.py`. Nothing else has to
 * change: the generated table is keyed by filename, so a new PNG becomes a new
 * entry and `PortraitArt` picks it up.
 *
 * **Why inline rather than `require` the file.** A required image becomes a
 * separate hashed asset that the bundle fetches by URL at runtime, and that
 * URL has to survive the artifact host. It did not: Metro writes absolute
 * `/assets/...`, the artifact is not served at a host root, and the portraits
 * went out live and invisible. Rewriting the URLs to relative was the obvious
 * repair and it still did not work on the author's screen.
 *
 * At that point the right move was to stop repairing the path and remove it.
 * A data URI is part of the bundle: there is no second request, nothing to
 * publish alongside, nothing to cache separately, and no way for the host's
 * path scheme to be wrong. The cost is bundle size, and quantising the PNGs
 * first makes it small — about 17KB of base64 per speaker, so the whole cast
 * is under two hundred.
 *
 * If these ever become large final art rather than placeholders, this is the
 * decision to revisit — but revisit it by *testing from a nested path*, which
 * is what would have caught the original bug.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'assets/portraits');

const entries = readdirSync(DIR)
  .filter((name) => name.endsWith('.png'))
  .sort()
  .map((name) => {
    const id = name.replace(/\.png$/, '');
    const base64 = readFileSync(join(DIR, name)).toString('base64');
    return { id, name, base64 };
  });

const header = `/**
 * Portrait art, inlined.
 *
 * GENERATED by \`scripts/inline-portraits.mjs\` from \`assets/portraits/\` —
 * do not edit by hand. Add a PNG there and re-run it.
 *
 * These are data URIs rather than required files on purpose. A required image
 * becomes a separate asset fetched by URL at runtime, and that URL has to
 * survive the artifact host; it did not, and the portraits shipped live and
 * invisible twice over. Inlined, there is no second request and no path to get
 * wrong. The PNGs are quantised first, so a speaker costs about 17KB.
 */

export const PORTRAIT_URIS: Record<string, string> = {
`;

const body = entries
  .map((e) => `  ${e.id}: 'data:image/png;base64,${e.base64}',`)
  .join('\n');

writeFileSync(join(ROOT, 'lib/portraits.ts'), `${header}${body}\n};\n`);

const total = entries.reduce((sum, e) => sum + e.base64.length, 0);
console.log(`inlined ${entries.length} portraits, ${(total / 1024).toFixed(0)}KB of base64:`);
for (const e of entries) console.log(`  ${e.id.padEnd(16)} ${(e.base64.length / 1024).toFixed(1)}KB`);
